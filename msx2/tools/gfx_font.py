DAKU = "ガギグゲゴザジズゼゾダヂヅデドバビブベボヴ"
DAKU_BASE = "カキクケコサシスセソタチツテトハヒフヘホウ"
HANDAKU = "パピプペポ"
HANDAKU_BASE = "ハヒフヘホ"


def glyph(ch):
    """8 行の文字列（'#' と '.'）を返す"""
    if ch in G:
        return G[ch]
    if ch in DAKU:
        base = [list(r) for r in G[DAKU_BASE[DAKU.index(ch)]]]
        for r in range(0, 2):
            for c in range(4, 7):
                base[r][c] = '.'
        base[1][6] = '.'
        for (r, c) in ((0, 5), (1, 5), (0, 7), (1, 7)):
            base[r][c] = '#'
        # 右上の画（1 行目の 5,6 列）を空けて濁点を読みやすくする
        base[1][4] = base[1][4] if base[1][3] == '#' else '.'
        return ["".join(r) for r in base]
    if ch in HANDAKU:
        base = [list(r) for r in G[HANDAKU_BASE[HANDAKU.index(ch)]]]
        for r in range(0, 3):
            for c in range(4, 8):
                base[r][c] = '.'
        for (r, c) in ((0, 6), (1, 5), (1, 7), (2, 6)):
            base[r][c] = '#'
        return ["".join(r) for r in base]
    raise KeyError(ch)


def glyph_bytes(ch):
    out = []
    for r in glyph(ch):
        b = 0
        for i, c in enumerate(r.ljust(8, '.')[:8]):
            if c == '#':
                b |= 0x80 >> i
        out.append(b)
    return out


ALL_CHARS = list(G.keys()) + list(DAKU) + list(HANDAKU)

if __name__ == "__main__":
    from PIL import Image
    chars = ALL_CHARS
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    im = Image.new("RGB", (cols * 9 + 1, rows * 9 + 1), (40, 40, 40))
    px = im.load()
    for i, ch in enumerate(chars):
        gx, gy = (i % cols) * 9 + 1, (i // cols) * 9 + 1
        for r, row in enumerate(glyph(ch)):
            for c, v in enumerate(row.ljust(8, '.')[:8]):
                px[gx + c, gy + r] = (255, 255, 255) if v == '#' else (0, 0, 0)
    im = im.resize((im.width * 4, im.height * 4), Image.NEAREST)
    im.save("../build/font_preview.png")
    print(len(chars), "glyphs")
