def fence_y(x):
    """x におけるフェンスの下端（芝との境）の y。ポールより外は None"""
    if x < FENCE[0][0] or x > FENCE[-1][0]:
        return None
    for (x0, y0), (x1, y1) in zip(FENCE, FENCE[1:]):
        if x0 <= x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return None


def is_fair(x, y):
    dx = abs(x - HOME[0])
    dy = HOME[1] - y
    return dy >= 0 and dx * 69 <= dy * 92
