def shift(rows, dx):
    """左右にずらす（体を前へ傾けるとき）"""
    out = []
    for r in rows:
        if dx < 0:
            out.append(r[-dx:] + "." * (-dx))
        else:
            out.append("." * dx + r[:len(r) - dx])
    return out


